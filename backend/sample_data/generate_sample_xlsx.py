"""Generate a multi-sheet XLSX sample workbook for the import center."""
from __future__ import annotations

import csv
from pathlib import Path

from openpyxl import Workbook

HERE = Path(__file__).resolve().parent


def main() -> None:
    csv_path = HERE / "sample_seller_leads.csv"
    with csv_path.open("r", encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.reader(fh))

    wb = Workbook()

    ws1 = wb.active
    ws1.title = "Seller Leads"
    for row in rows:
        ws1.append(row)

    ws2 = wb.create_sheet("Older List")
    ws2.append(["Seller", "Cell", "Email", "Address", "City", "ST", "ZIP", "Status", "Notes"])
    older = [
        ["Ronald Meyers", "6145550301", "ron.m@example.com", "771 Broad St", "Columbus", "OH", "43206", "New", "Pre-foreclosure; bank notice on the door."],
        ["Evelyn Hart", "614-555-0302", "evelyn.h@example.com", "3309 Sunbury Rd", "Blacklick", "OH", "43004", "Contact Made", "Wants to wait until spring."],
        ["Curtis Boone", "", "cboone@example.com", "18 Holloway Dr", "Westerville", "OH", "43081", "Not Contacted", "Email only in this list."],
        ["Sandra Whitlock", "614.555.0304", "", "640 Parkview Ave", "Columbus", "OH", "43215", "Follow Up", "Callback requested for Thursday."],
    ]
    for row in older:
        ws2.append(row)

    ws3 = wb.create_sheet("Summary")
    ws3.append(["Generated by", "generate_sample_xlsx.py"])
    ws3.append(["Sheets", "Seller Leads (matches the CSV), Older List (alternate headers)"])

    out = HERE / "sample_seller_leads.xlsx"
    wb.save(out)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
